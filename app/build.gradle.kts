/**
 * Release signing is opt-in and never committed. Create `keystore.properties` at
 * the repository root (it is git-ignored) with storeFile/storePassword/keyAlias/
 * keyPassword to produce a signed release; otherwise release builds stay unsigned
 * and the build still succeeds from a clean checkout.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseSigning = keystoreProperties.getProperty("storeFile") != null

